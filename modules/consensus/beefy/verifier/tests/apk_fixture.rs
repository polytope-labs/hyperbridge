//! The runtime verifier against the fixture `BlsApkBeefy.sol` verifies.
//!
//! Lives out here rather than in the unit tests because those pull `w3f-bls` and its arkworks 0.4,
//! while `crate::apk` is on 0.5, and the two cannot both be in scope in one test binary.

#![cfg(feature = "apk")]

use alloy_sol_types::SolType;
use beefy_verifier::apk::{count_signers, verify_apk_consensus};
use beefy_verifier_primitives::{ApkConsensusMessage, ApkConsensusState};
use ismp_abi::bls_apk_beefy::BlsApkBeefy;
use polkadot_sdk::*;
use primitive_types::H256;

/// Generated by the circuit's trusted setup, and the same key that goes into pallet storage.
const VERIFYING_KEY: &[u8] =
	include_bytes!("../../../../../evm/tests/foundry/fixtures/apk-verifying-key.bin");

struct TestHost;

impl ismp::messaging::Keccak256 for TestHost {
	fn keccak256(bytes: &[u8]) -> H256 {
		sp_io::hashing::keccak_256(bytes).into()
	}
}

/// The two verifiers have to agree, since they check the same proofs against the same commitment.
/// This runs the Solidity test's fixture, byte for byte, through the Rust path: same ABI encoding
/// off the wire, same verifying key, same expectations.
///
/// A disagreement here is the expensive kind to find later, because in production it looks like a
/// proof that verifies on one chain and not the other with nothing to explain why.
///
///   cargo test -p beefy-verifier --features apk --test apk_fixture -- --nocapture
#[test]
fn apk_verifier_agrees_with_solidity() {
	let decode_hex = |raw: &str| hex::decode(raw.trim().trim_start_matches("0x")).expect("hex");
	let state_bytes = decode_hex(include_str!(
		"../../../../../evm/tests/foundry/fixtures/bls-apk-beefy-state.hex"
	));
	let proof_bytes = decode_hex(include_str!(
		"../../../../../evm/tests/foundry/fixtures/bls-apk-beefy-proof.hex"
	));

	// The state is one abi-encoded struct, the proof is the two the client's `verify` takes as
	// separate arguments, which is why they decode differently.
	let trusted: ApkConsensusState =
		<BlsApkBeefy::BlsApkConsensusState as SolType>::abi_decode(&state_bytes)
			.expect("state decodes")
			.try_into()
			.expect("state converts");
	let proof: ApkConsensusMessage =
		<BlsApkBeefy::BlsApkBeefyConsensusProof as SolType>::abi_decode_params(&proof_bytes)
			.expect("proof decodes")
			.try_into()
			.expect("proof converts");

	let signing_set = proof.mmr.commitment.validator_set_id;
	let signers = count_signers(&proof.mmr.bitlist);

	let (state, headers) = verify_apk_consensus::<TestHost>(trusted.clone(), proof, VERIFYING_KEY)
		.expect("the proof solidity verifies must verify here too");

	assert!(
		state.latest_beefy_height > trusted.latest_beefy_height,
		"height should advance, was {} now {}",
		trusted.latest_beefy_height,
		state.latest_beefy_height
	);
	assert_eq!(headers.len(), 1, "should finalize the registered parachain");
	assert_eq!(headers[0].para_id, 4009, "should be para 4009");

	println!(
		"apk proof verified in the runtime path: set {signing_set}, {signers} signers, beefy height {} -> {}",
		trusted.latest_beefy_height, state.latest_beefy_height
	);
}
